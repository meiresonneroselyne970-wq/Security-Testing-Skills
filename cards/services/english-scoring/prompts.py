# ============================================================
# 系统提示词查找
# ============================================================

def get_system_prompt(card_type: str) -> str:
    """根据卡片类型返回对应的系统提示词"""
    mapping = {
        "english_word":     WORD_SYSTEM_PROMPT,
        "english_sentence": SENTENCE_SYSTEM_PROMPT,
        "english_input":    INPUT_SYSTEM_PROMPT,
    }
    return mapping.get(card_type, SENTENCE_SYSTEM_PROMPT)


# ============================================================
# 用户提示词构建
# ============================================================

def build_user_prompt(card_type: str, target_text: str, recognized_text: str) -> str:
    """
    根据卡片类型构建用户提示词。

    Args:
        card_type: 'english_word' | 'english_sentence' | 'english_input'
        target_text: 参考文本（目标单词/句子）
        recognized_text: 语音识别文本（用户实际发音）

    Returns:
        构建好的用户提示词字符串
    """
    if card_type == "english_word":
        return f"""请对以下英语单词的跟读进行评分：

【参考单词】{target_text}
【学生发音识别文本】{recognized_text}

请根据学生的发音识别文本与参考单词的对比，从发音准确度、完整性、流利度三个维度进行评分。
注意：语音识别可能存在误差，请结合参考单词和识别文本之间的相似度做合理推断。"""

    elif card_type == "english_sentence":
        return f"""请对以下英语句子的跟读进行评分：

【参考句子】{target_text}
【学生发音识别文本】{recognized_text}

请根据学生的发音识别文本与参考句子的对比，从发音准确度、完整性、流利度、语调自然度四个维度进行评分。
注意：语音识别可能存在误差，请结合参考句子和识别文本之间的词语重叠情况做合理推断。"""

    elif card_type == "english_input":
        return f"""请对以下英语句子的跟读进行评分：

【学生输入的句子】{target_text}
【学生发音识别文本】{recognized_text}

请根据学生的发音识别文本与输入句子的对比，从发音准确度、完整性、流利度、语调自然度、语法与表达五个维度进行评分。
注意：语音识别可能存在误差，请结合输入句子和识别文本之间的词语重叠情况做合理推断。"""

    else:
        return f"【参考文本】{target_text}\n【识别文本】{recognized_text}"
